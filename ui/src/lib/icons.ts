const cache = new Map<string, string>();

/** Strip the licence comment and fixed sizing so CSS controls the size. */
export function iconSvg(name: string): string {
  let svg = cache.get(name);
  if (svg !== undefined) return svg;
  const src = raw[name] ?? raw['box'];
  svg = src
    .replace(/<!--[\s\S]*?-->/g, '')
    // Only the root element's sizing/class: inner <rect width=...> must stay.
    .replace(/<svg\b[^>]*>/, (tag) => tag.replace(/\s(?:width|height|class)="[^"]*"/g, ''))
    .trim();
  cache.set(name, svg);
  return svg;
}

